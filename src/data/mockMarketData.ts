// Helper to generate realistic curve points
function generateChartPoints(basePrice: number, volatility: number, trend: number, count: number = 30): ChartDataPoint[] {
  const points: ChartDataPoint[] = [];
  let current = basePrice;
  const times = [
    '09:30 AM', '09:45 AM', '10:00 AM', '10:15 AM', '10:30 AM', '10:45 AM',
    '11:00 AM', '11:15 AM', '11:30 AM', '11:45 AM', '12:00 PM', '12:15 PM',
    '12:30 PM', '12:45 PM', '01:00 PM', '01:15 PM', '01:30 PM', '01:45 PM',
    '02:00 PM', '02:15 PM', '02:30 PM', '02:45 PM', '03:00 PM', '03:15 PM',
    '03:30 PM', '03:45 PM', '04:00 PM'
  ];

  for (let i = 0; i < count; i++) {
    const time = times[i % times.length];
    const change = (Math.random() - 0.48 + trend * 0.05) * volatility;
    current = +(current + change).toFixed(2);
    const volume = Math.floor(Math.random() * 50 + 20);
    const isUp = change >= 0;
    points.push({ time, price: current, volume, isUp });
  }
  return points;
}

